#!/bin/bash
# Download SLC City Council public comment PDFs, organized by year
set -euo pipefail

BASE_DIR="$(cd "$(dirname "$0")" && pwd)"

# Create year directories
for year in 2020 2021 2022 2023 2024 2025 2026; do
    mkdir -p "$BASE_DIR/$year"
done

# Track results
total=0
success=0
failed=0
fail_list=""

download() {
    local url="$1"
    # Normalize to https and fix backslashes
    url=$(echo "$url" | sed 's|http://|https://|' | sed 's|\\|/|g')

    # Extract year from URL path
    local year=$(echo "$url" | grep -oE '20[0-9]{2}' | head -1)
    # Extract filename, decode %20 to spaces then convert to underscores
    local filename=$(basename "$url" | python3 -c "import sys, urllib.parse; print(urllib.parse.unquote(sys.stdin.read().strip()))" | tr ' ' '_')

    total=$((total + 1))
    echo "[$total] Downloading: $filename -> $year/"

    if curl -sfL --max-time 60 -o "$BASE_DIR/$year/$filename" "$url"; then
        success=$((success + 1))
    else
        failed=$((failed + 1))
        fail_list="$fail_list\n  $url"
        echo "  FAILED: $url"
    fi
}

echo "=== SLC City Council Public Comments PDF Downloader ==="
echo "Saving to: $BASE_DIR"
echo ""

