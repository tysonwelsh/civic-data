#!/usr/bin/env python3
"""build_finance.py — Utah County campaign-finance STATED-TOTALS layer (module-local builder).

DERIVED. Regenerate with:  python3 utah_county/campaign_finance/build_finance.py

Inputs (curated, hand-verified — corrections go THERE, never into the CSVs):
    index.csv        one row per retained filing (regenerated by build_index.py)
    vision/*.json    one curated vision transcript per filing, keyed
                     sha1(index.csv `path`)[:8] — the repo-wide cf-vision cache convention

Outputs (SCHEMA.md §2/§3/§4 column contract, exactly):
    filing_totals.csv   one row per FILING (per REPORT for bundled PDFs)
    contributions.csv   the MACHINE-READABLE itemized layer (+ the trailing `geometry`, §2a)
    expenditures.csv    ditto

Why a module-local builder and not the shared engine's `driver.run()`: 245 of 263 filings are
tesseract OCR of HANDWRITTEN forms whose figures exist only as curated vision transcripts, and
`driver.run()` would rewrite all three CSVs from one parse pass. `utahcounty_schedab` IS now
registered in the shared registry (both printed variants), so this builder keeps the
vision-based stated totals and calls that family for the ITEMIZED layer of the **17
machine-readable filings** only (`index.format == 'text'`, i.e. `pdftotext -layout`, never an
OCR sidecar — CLAUDE.md: "Do not read text/*.txt as a transcript").

THE ITEMIZED LAYER (TRANCHE 3 Phase A, 2026-08-02)
  * `reconcile_cash_only=True` — the contribution anchor (Column A / Box B) is the CASH figure,
    and in-kind is a separate printed line, so the reconciliation sum counts cash rows only.
  * Every emitted side is RECONCILIATION-GATED against the stated total this module already
    publishes; a side that does not reconcile emits NOTHING plus a reason. No `stated_*` value
    is ever recomputed from an itemization.
  * THE COMPOUND `+Inkind` CELL. On the v.12.23 sheet Box B prints BOTH figures in one cell
    (`168872.24 +Inkind 7670.68`). This module's `money()` deliberately refuses to reduce that
    to one number, so `stated_total_contributions` is **BLANK** there — and stays blank. The
    family splits the cell on the form's own printed marker and reports the two parts
    separately, which is a DIVERGENCE from the published blank; the divergence is recorded in
    `notes`, the published total is not changed, and the family's itemized rows are published
    ALONGSIDE it with `reconciles_contrib` left blank (unknown) because there is no published
    figure to test against. What IS proven, and is stated in the note, is that the cash rows
    sum EXACTLY to the form's own printed cash component.
  * IN-KIND is asserted only where the family's per-page calibration reproduces the ledger's
    own printed IN-KIND total to the cent; otherwise the family reports every row as cash and
    flags it. That decision is the family's and is passed through untouched.

THE PROMOTION REGIME (documented, and the reason `filing_regime` says `per-period`):
both forms print a PER-PERIOD figure and a CUMULATIVE figure side by side.
    legacy_colAB  Column A "Total this Period"   | Column B "Year-to-Date Total"
    modern_boxAF  Box B / Box D  "this Period"   | Box C / Box E  "Year to Date"
`stated_total_contributions` / `stated_total_expenditures` carry the **PER-PERIOD** figure —
the increment. The cumulative figures are kept verbatim in `notes` (`ytd_contrib=` /
`ytd_expend=`) and in full in the vision transcript, and are **NEVER summed as increments**.
A cycle total is therefore Σ per-period rows, cross-checked against the LAST report's
cumulative — never a sum of the cumulative column.
"""
